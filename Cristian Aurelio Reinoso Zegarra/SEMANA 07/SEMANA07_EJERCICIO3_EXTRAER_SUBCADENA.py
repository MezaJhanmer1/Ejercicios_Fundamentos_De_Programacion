# guardamos un texto
texto = "Análisis de Datos con Python"

# cortamos un pedazo del texto
# texto[12:17] significa: desde la posición 12 hasta antes de la 17
# Ese pedazo corresponde a la palabra "Datos"
datos = texto[12:17]

# cortamos otro pedazo
# texto[22:28] significa: desde la posición 22 hasta antes de la 28
# Ese pedazo corresponde a la palabra "Python"
python = texto[22:28]

# mostramos los resultados
print(datos)   # Datos
print(python)  # Python