# Creamos una cadena que tiene espacios al inicio y al final
cadena = " Python es divertido "

# strip() elimina los espacios que están al inicio y al final
cadena_limpia = cadena.strip()

# len() cuenta la cantidad de caracteres de la cadena limpia
cantidad = len(cadena_limpia)

# Mostramos la cadena después de eliminar los espacios
print("Cadena limpia:", cadena_limpia)

# Mostramos la cantidad de caracteres
print("Cantidad de caracteres:", cantidad)